// Builds src/v4seed.js (the game history v4's ratings start from) out of football-data.co.uk style CSV files.
// Usage:  node tools/make-v4-seed.mjs "<folder with the CSVs>"
// Expected files in the folder: EPL24/25/26.csv, Championship*, Bundes*, BundesSecond*, Spain*, SpainSecond*,
// SeriA*, French*, Netherlands*  (24 = 2024-25 ... 26 = 2026-27), plus USA.csv and MEX.csv.
// The Hub keeps ratings fresh from live games after the seed's last date, so re-running this is optional.
// Each league also carries ratings fitted on its history ('r'), which the Hub uses as its starting point.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { fit } from '../src/v4core.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const dir = process.argv[2];
if (!dir) { console.error('Pass the folder that holds the CSV files.'); process.exit(1); }
const { espn, alias } = JSON.parse(fs.readFileSync(path.join(here, 'v4-names.json'), 'utf8'));
const DAY = 86400000, WINDOW_DAYS = 900;

function splitCSV(line) { const o = []; let cur = '', q = false; for (const ch of line) { if (ch === '"') q = !q; else if (ch === ',' && !q) { o.push(cur); cur = ''; } else cur += ch; } o.push(cur); return o; }
function readCSV(file) { const L = fs.readFileSync(path.join(dir, file), 'utf8').replace(/^﻿/, '').split(/\r?\n/).filter(Boolean); const head = splitCSV(L[0]); return L.slice(1).map(l => { const c = splitCSV(l), o = {}; head.forEach((h, i) => { o[h] = c[i]; }); return o; }); }
const day = s => { const [d, m, y] = s.split('/').map(Number); return Math.floor(Date.UTC(y < 100 ? 2000 + y : y, m - 1, d) / DAY); };

const SOURCES = [
  ['eng.1', ['EPL24', 'EPL25', 'EPL26'], 'eu'], ['eng.2', ['Championship24', 'Championship25', 'Championship26'], 'eu'],
  ['ger.1', ['Bundes24', 'Bundes25', 'Bundes26'], 'eu'], ['ger.2', ['BundesSecond24', 'BundesSecond25', 'BundesSecond26'], 'eu'],
  ['esp.1', ['Spain24', 'Spain25', 'Spain26'], 'eu'], ['esp.2', ['SpainSecond24', 'SpainSecond25', 'SpainSecond26'], 'eu'],
  ['ita.1', ['SeriA24', 'SeriA25', 'SeriA26'], 'eu'], ['fra.1', ['French24', 'French25', 'French26'], 'eu'],
  ['ned.1', ['Netherlands24', 'Netherlands25', 'Netherlands26'], 'eu'], ['usa.1', ['USA'], 'usa'], ['mex.1', ['MEX'], 'mex'],
];
const out = {}; let problems = 0;
for (const [slug, files, kind] of SOURCES) {
  let rows = [];
  for (const f of files) for (const r of readCSV(f + '.csv')) {
    if (kind === 'eu') { if (r.FTHG === '' || r.FTHG === undefined || !r.Date) continue; rows.push({ d: day(r.Date), h: r.HomeTeam, a: r.AwayTeam, hg: +r.FTHG, ag: +r.FTAG }); }
    else { if (r.HG === '' || r.HG === undefined) continue; rows.push({ d: day(r.Date), h: r.Home, a: r.Away, hg: +r.HG, ag: +r.AG }); }
  }
  rows.sort((x, y) => x.d - y.d);
  const last = rows[rows.length - 1].d; rows = rows.filter(r => r.d >= last - WINDOW_DAYS);
  const current = new Set(espn[slug]); const teams = [], idx = new Map();
  const id = name => { const n = alias[name] && current.has(alias[name]) ? alias[name] : name; if (!idx.has(n)) { idx.set(n, teams.length); teams.push(n); } return idx.get(n); };
  const g = rows.map(r => [r.d, id(r.h), id(r.a), r.hg, r.ag]);
  const missing = espn[slug].filter(n => !idx.has(n));
  if (missing.length) { problems++; console.error(`${slug}: ESPN clubs with no games in the files: ${missing.join(', ')}`); }
  // Ratings as of the day after the last game: the Hub starts from these and only refines them with live games.
  const asOf = (last + 1) * DAY;
  const r = fit(slug, g.map(([d, h, a, hg, ag]) => ({ d, h: teams[h], a: teams[a], hg, ag })), asOf);
  out[slug] = { through: new Date(last * DAY).toISOString().slice(0, 10), teams, g, r };
  console.log(slug.padEnd(7), String(g.length).padStart(5), 'games, through', out[slug].through, ',', teams.length, 'clubs');
}
const file = path.join(here, '..', 'src', 'v4seed.js');
fs.writeFileSync(file, '// Generated by tools/make-v4-seed.mjs. Game history for the v4 ratings: [day number, home club, away club, home goals, away goals].\n// Day number = days since 1970-01-01. Club numbers index into "teams" (ESPN display names).\nexport default ' + JSON.stringify(out) + ';\n');
console.log('wrote', file, (fs.statSync(file).size / 1024).toFixed(0) + ' KB', problems ? `(${problems} warnings)` : '');
