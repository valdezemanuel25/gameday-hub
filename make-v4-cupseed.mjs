// Builds src/v4cupseed.js (Champions League + Europa League history for the v4 cup model) from the
// fixture / result CSVs, e.g.  node tools/make-v4-cupseed.mjs "C:\Users\you\Documents\Soccer\Cups"
// The folder needs champions-league-<year>-UTC.csv and europa-league-<year>-UTC.csv files (name may have a prefix).
// tools/v4-cup-extra.json adds results played after the files were exported.
import fs from 'fs';
import path from 'path';
import seed from '../src/v4seed.js';
import { info, fitCup, CUP } from '../src/v4cup.js';

const dir = process.argv[2];
if (!dir) { console.error('Usage: node tools/make-v4-cupseed.mjs <folder with the cup CSVs>'); process.exit(1); }
const DAY = 86400000;
const csv = line => { const o = []; let c = '', q = false; for (let i = 0; i < line.length; i++) { const ch = line[i]; if (ch === '"') { if (q && line[i + 1] === '"') { c += '"'; i++; } else q = !q; } else if (ch === ',' && !q) { o.push(c); c = ''; } else c += ch; } o.push(c); return o; };
const rows = [];
for (const f of fs.readdirSync(dir)) {
  const m = /(champions-league|europa-league)-(\d{4})-UTC\.csv$/i.exec(f); if (!m) continue;
  const comp = m[1].toLowerCase().startsWith('champions') ? 0 : 1;
  for (const line of fs.readFileSync(path.join(dir, f), 'utf8').split(/\r?\n/).slice(1).filter(Boolean)) {
    const c = csv(line), [dd, mm, rest] = c[2].split('/'), yy = rest.split(' ')[0];
    const r = /^(\d+)\s*-\s*(\d+)$/.exec((c[6] || '').trim());
    rows.push({ d: Math.floor(Date.UTC(+yy, +mm - 1, +dd) / DAY), c: comp, h: c[4].trim(), a: c[5].trim(), hg: r ? +r[1] : null, ag: r ? +r[2] : null });
  }
}
const extra = JSON.parse(fs.readFileSync(new URL('./v4-cup-extra.json', import.meta.url), 'utf8')).games;
for (const [comp, date, h, a, hg, ag] of extra) {
  const d = Math.floor(Date.parse(date) / DAY), c = comp === 'CL' ? 0 : 1;
  const x = rows.find(r => r.d === d && r.c === c && r.h === h && r.a === a);
  if (x) { if (x.hg == null) { x.hg = hg; x.ag = ag; } } else rows.push({ d, c, h, a, hg, ag });
}
const played = rows.filter(r => r.hg != null).sort((x, y) => x.d - y.d);
const unknown = [...new Set(played.flatMap(r => [r.h, r.a]).filter(n => !info.has(n)))];
if (unknown.length) { console.error('Clubs missing from src/v4cupnames.js:', unknown.join(', ')); process.exit(1); }
const teams = [...new Set(played.flatMap(r => [r.h, r.a]))];
const ti = new Map(teams.map((t, i) => [t, i]));
const through = new Date(Math.max(...played.map(r => r.d)) * DAY).toISOString().slice(0, 10);
const domOf = (slug, name) => seed[slug]?.r.t[name] || null;
const games = played.map(r => ({ d: r.d, c: r.c, h: r.h, a: r.a, hg: r.hg, ag: r.ag }));
const r = fitCup(games, domOf, (Math.floor(Date.parse(through) / DAY) + 1) * DAY);
const out = { through, teams, g: played.map(r => [r.d, r.c, ti.get(r.h), ti.get(r.a), r.hg, r.ag]), r };
fs.writeFileSync(new URL('../src/v4cupseed.js', import.meta.url),
  '// Generated by tools/make-v4-cupseed.mjs. Champions League (0) and Europa League (1) results for the v4 cup model:\n// [day number, competition, home club, away club, home goals, away goals]. Club numbers index into "teams" (names from src/v4cupnames.js).\nexport default ' + JSON.stringify(out) + ';\n');
console.log(`${played.length} played games through ${through}, ${teams.length} clubs, ${rows.length - played.length} fixtures not yet played (not stored)`);
